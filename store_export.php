<?php
include 'auth.php';
include 'db.php';

$type = $_GET['type'] ?? 'stock';
$date = date('Y-m-d');

if($type == 'stock'){
    // Current Stock Export
    header('Content-Type: text/csv; charset=utf-8');
    header('Content-Disposition: attachment; filename=IT_Store_Stock_'.$date.'.csv');

    $output = fopen('php://output', 'w');

    // Title row
    fputcsv($output, ['VCM IT Store — Current Stock Report']);
    fputcsv($output, ['Generated On: '.$date]);
    fputcsv($output, ['Generated By: '.$_SESSION['name']]);
    fputcsv($output, []); // blank row

    // Header
    fputcsv($output, ['#', 'Item Name', 'Category', 'Current Stock', 'Min Stock', 'Unit', 'Status', 'Description']);

    $items = mysqli_query($conn, "SELECT * FROM store_items ORDER BY category, name");
    $i = 1;
    while($row = mysqli_fetch_assoc($items)){
        $qty   = $row['quantity'];
        $min   = $row['min_quantity'];
        if($qty == 0)      $status = 'OUT OF STOCK';
        elseif($qty <= $min) $status = 'LOW STOCK';
        else                  $status = 'OK';

        fputcsv($output, [
            $i++,
            $row['name'],
            $row['category'],
            $row['quantity'],
            $row['min_quantity'],
            $row['unit'],
            $status,
            $row['description']
        ]);
    }

    // Summary
    $total    = mysqli_fetch_assoc(mysqli_query($conn,"SELECT COUNT(*) as c FROM store_items"))['c'];
    $low      = mysqli_fetch_assoc(mysqli_query($conn,"SELECT COUNT(*) as c FROM store_items WHERE quantity <= min_quantity AND quantity > 0"))['c'];
    $out      = mysqli_fetch_assoc(mysqli_query($conn,"SELECT COUNT(*) as c FROM store_items WHERE quantity = 0"))['c'];

    fputcsv($output, []);
    fputcsv($output, ['--- SUMMARY ---']);
    fputcsv($output, ['Total Items', $total]);
    fputcsv($output, ['Low Stock',   $low]);
    fputcsv($output, ['Out of Stock',$out]);

    fclose($output);

} elseif($type == 'log'){
    // IN/OUT Log Export
    $from = $_GET['from'] ?? date('Y-m-01'); // month start
    $to   = $_GET['to']   ?? date('Y-m-d');  // today

    header('Content-Type: text/csv; charset=utf-8');
    header('Content-Disposition: attachment; filename=IT_Store_Log_'.$from.'_to_'.$to.'.csv');

    $output = fopen('php://output', 'w');

    fputcsv($output, ['VCM IT Store — IN/OUT Log Report']);
    fputcsv($output, ['Period: '.$from.' to '.$to]);
    fputcsv($output, ['Generated By: '.$_SESSION['name']]);
    fputcsv($output, []);

    fputcsv($output, ['#', 'Date', 'Type', 'Item Name', 'Category', 'Quantity', 'Employee', 'Department', 'Purpose', 'Remarks', 'Done By']);

    $from_safe = mysqli_real_escape_string($conn, $from);
    $to_safe   = mysqli_real_escape_string($conn, $to);

    $logs = mysqli_query($conn,"SELECT l.*, i.category FROM store_log l 
        LEFT JOIN store_items i ON i.id = l.item_id
        WHERE DATE(l.action_date) BETWEEN '$from_safe' AND '$to_safe'
        ORDER BY l.action_date DESC");

    $i = 1;
    $total_in = 0; $total_out = 0;
    while($row = mysqli_fetch_assoc($logs)){
        if($row['type'] == 'IN')  $total_in  += $row['quantity'];
        if($row['type'] == 'OUT') $total_out += $row['quantity'];

        fputcsv($output, [
            $i++,
            date('d-m-Y H:i', strtotime($row['action_date'])),
            $row['type'],
            $row['item_name'],
            $row['category'] ?? '',
            $row['quantity'],
            $row['employee']   ?? '',
            $row['department'] ?? '',
            $row['purpose']    ?? '',
            $row['remarks']    ?? '',
            $row['done_by']    ?? ''
        ]);
    }

    fputcsv($output, []);
    fputcsv($output, ['--- SUMMARY ---']);
    fputcsv($output, ['Total IN',  $total_in]);
    fputcsv($output, ['Total OUT', $total_out]);

    fclose($output);
}
exit;
?>
